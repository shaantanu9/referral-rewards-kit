#!/usr/bin/env node
// Generates js/packages/referral-core/src/l10n/messages.ts from the Flutter package's ARB files, so the JS strings
// stay identical to the Dart ones. Run `pnpm gen:l10n` after an ARB changes; the output is committed.
//
// Placeholders and their order come from the English ARB's `@key.placeholders` (the order Flutter's gen-l10n uses
// for the method parameters). `int` placeholders become `number`, everything else `string`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const jsRoot = join(here, '..');
const arbDir = join(jsRoot, '..', 'packages', 'referral_kit', 'lib', 'src', 'l10n');
const out = join(jsRoot, 'packages', 'referral-core', 'src', 'l10n', 'messages.ts');

const read = (locale) => JSON.parse(readFileSync(join(arbDir, `referral_kit_${locale}.arb`), 'utf8'));
const en = read('en');
const others = { hi: read('hi'), id: read('id') };

const keys = Object.keys(en).filter((k) => !k.startsWith('@'));
const params = {};
const docs = {};
for (const k of keys) {
  const meta = en[`@${k}`] ?? {};
  const ph = meta.placeholders ?? {};
  params[k] = Object.entries(ph).map(([name, p]) => ({ name, type: p.type === 'int' || p.type === 'num' || p.type === 'double' ? 'number' : 'string' }));
  if (meta.description) docs[k] = meta.description;
}

const q = (s) => JSON.stringify(s);
const lines = [];
lines.push('// GENERATED by js/scripts/gen-l10n.mjs from packages/referral_kit/lib/src/l10n/referral_kit_{en,hi,id}.arb.');
lines.push('// Do not edit by hand: change the ARB files and run `pnpm gen:l10n`.');
lines.push('/* eslint-disable */');
lines.push('');
lines.push('/** Every message key of the referral kit (the ARB keys). */');
lines.push(`export type ReferralMessageKey =\n${keys.map((k) => `  | ${q(k)}`).join('\n')};`);
lines.push('');
lines.push('/** Placeholder names per key, in the order the Dart getters / methods take them. */');
lines.push('export const referralMessageParams: { readonly [K in ReferralMessageKey]: readonly string[] } = {');
for (const k of keys) lines.push(`  ${k}: [${params[k].map((p) => q(p.name)).join(', ')}],`);
lines.push('};');
lines.push('');
lines.push('/**');
lines.push(' * The localised strings, one member per ARB key: a string for a message without placeholders, a function (same');
lines.push(' * parameter order as the Dart `ReferralKitLocalizations`) for one with placeholders. `localeName` is `en`, `hi` or `id`.');
lines.push(' */');
lines.push('export interface ReferralKitLocalizations {');
lines.push('  readonly localeName: string;');
for (const k of keys) {
  if (docs[k]) lines.push(`  /** ${docs[k].replace(/\*\//g, '*\\/')} */`);
  const ps = params[k];
  if (ps.length === 0) lines.push(`  readonly ${k}: string;`);
  else lines.push(`  ${k}(${ps.map((p) => `${p.name}: ${p.type}`).join(', ')}): string;`);
}
lines.push('}');
lines.push('');
const emit = (name, arb, all) => {
  lines.push(`export const ${name}: ${all ? 'Readonly<Record<ReferralMessageKey, string>>' : 'Readonly<Partial<Record<ReferralMessageKey, string>>>'} = {`);
  for (const k of keys) {
    if (typeof arb[k] === 'string') lines.push(`  ${k}: ${q(arb[k])},`);
  }
  lines.push('};');
  lines.push('');
};
emit('referralMessagesEn', en, true);
const missing = {};
for (const [loc, arb] of Object.entries(others)) {
  emit(`referralMessages${loc[0].toUpperCase()}${loc.slice(1)}`, arb, false);
  missing[loc] = keys.filter((k) => typeof arb[k] !== 'string');
}
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${relative(process.cwd(), out)}: ${keys.length} keys`);
for (const [loc, m] of Object.entries(missing)) {
  if (m.length) console.log(`  ${loc}: ${m.length} keys fall back to English: ${m.join(', ')}`);
}
